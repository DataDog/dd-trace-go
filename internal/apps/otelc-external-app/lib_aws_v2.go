package main

import (
	"github.com/aws/aws-sdk-go-v2/aws"
	"github.com/aws/aws-sdk-go-v2/service/dynamodb"
)

func init() {
	registerLibrary("aws_v2", func() {
		_ = dynamodb.NewFromConfig(aws.Config{Region: "us-east-1"})
	})
}
