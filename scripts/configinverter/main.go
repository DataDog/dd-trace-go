func main() {
	const defaultRegistryOutput = "./internal/env"
	var (
		input        string
		output       string
		configOutput string
	)
	flag.StringVar(&input, "input", "./internal/env/supported_configurations.json", "Path to the input file")
	flag.StringVar(&output, "output", defaultRegistryOutput, "Path to the registry output directory")
	flag.StringVar(&configOutput, "config-output", "", "Path to the singleton output directory for generate-core (./internal/config with the default registry output)")
	flag.Parse()

	// Get command and keys from positional arguments
	args := flag.Args()
	if len(args) == 0 {
		slog.Error("no command provided")
		os.Exit(1)
	}

	command := args[0]

	var err error
	switch command {
	case "generate":
		err = generate(input, output, false, "")
	case "generate-core":
		if configOutput == "" && output == defaultRegistryOutput {
			configOutput = "./internal/config"
		}
		err = generate(input, output, true, configOutput)
	case "check":
		err = check(input)
	case "add":
		err = add(input, output, args[1:])
	default:
		err = fmt.Errorf("unknown command: %s", command)
	}

	if err != nil {
		slog.Error("error executing command", "error", err)
		os.Exit(1)
	}
	slog.Info("success executing command", "command", command)
}

type supportedConfiguration struct {
	Version                 string                                   `json:"version"`
	SupportedConfigurations map[string][]configurationImplementation `json:"supportedConfigurations"`
}

type configurationImplementation struct {
	Implementation       string   `json:"implementation"`
	Type                 string   `json:"type"`
	ConfigurationNames   []string `json:"configurationNames,omitempty"`
	InternalPropertyName string   `json:"internalPropertyName,omitempty"`
	Default              *string  `json:"default"`
	Allowed              string   `json:"allowed,omitempty"`
	Aliases              []string `json:"aliases,omitempty"`
	// Sensitive marks a configuration whose value must not be reported in
	// configuration telemetry. When set on any implementation of a key, that key
	// is emitted in the generated SensitiveConfigurations set.
	Sensitive bool `json:"sensitive,omitempty"`
}

// generate generates the supported configurations map from the supported configurations
// JSON file.
func generate(input, output string, compileSchema bool, configOutput string) error {
	cfg, err := getSupportedConfigurations(input)
	if err != nil {
		return fmt.Errorf("error getting supported configuration keys: %w", err)
	}

	keys := sortSupportedConfigurationsKeys(cfg)
	var initializers *jen.File
	if compileSchema {
		settings, err := compileConfigSchema(input)
		if err != nil {
			return err
		}
		keys = make([]string, 0, len(settings))
		for key := range settings {
			keys = append(keys, key)
		}
		sort.Strings(keys)
		if configOutput != "" {
			initializers, err = configInitializers(cfg, settings, keys)
			if err != nil {
				return err
			}
		}
	}
	patterns, err := allowedPatterns(cfg)
	if err != nil {
		return err
	}

	slog.Info("supported configuration keys count", "count", len(keys))

	f := jen.NewFilePath(output)
	f.HeaderComment("Unless explicitly stated otherwise all files in this repository are licensed")
	f.HeaderComment("under the Apache License Version 2.0.")
	f.HeaderComment("This product includes software developed at Datadog (https://www.datadoghq.com/).")
	f.HeaderComment("Copyright 2025 Datadog, Inc.")
	f.Comment("Code generated by github.com/DataDog/dd-trace-go/v2/scripts/configinverter. DO NOT EDIT.")
	f.Line()
	f.Comment("SupportedConfigurations is a map of supported configuration keys.")
	f.Var().Id("SupportedConfigurations").Op("=").Map(jen.String()).Struct().ValuesFunc(func(g *jen.Group) {
		for _, v := range keys {
			g.Add(jen.Line(), jen.Lit(v), jen.Op(":"), jen.Values())
		}
		g.Line()
	})
	f.Line()

	// Collect keys marked sensitive in any of their implementations.
	sensitiveKeys := sensitiveConfigurationKeys(cfg)

	f.Comment("SensitiveConfigurations is the set of configuration keys whose value must not be")
	f.Comment("reported in configuration telemetry. It is seeded from entries marked \"sensitive\": true")
	f.Comment("in supported_configurations.json.")
	f.Var().Id("SensitiveConfigurations").Op("=").Map(jen.String()).Struct().ValuesFunc(func(g *jen.Group) {
		for _, v := range sensitiveKeys {
			g.Add(jen.Line(), jen.Lit(v), jen.Op(":"), jen.Values())
		}
		g.Line()
	})
	f.Line()

	aliases := collectAliasMap(cfg)
	keysWithAliases := make([]string, 0, len(aliases))
	for k := range aliases {
		keysWithAliases = append(keysWithAliases, k)
	}
	if len(keysWithAliases) > 0 {
		slog.Info("keys with aliases", "count", len(keysWithAliases), "keys", keysWithAliases)
		sort.Strings(keysWithAliases)
	}

	f.Comment("KeyAliases maps canonical configuration keys to their known aliases.")
	f.Var().Id("KeyAliases").Op("=").Map(jen.String()).Index().String().ValuesFunc(func(g *jen.Group) {
		for _, v := range keysWithAliases {
			g.Add(jen.Line(), jen.Lit(v), jen.Op(":"), jen.ValuesFunc(func(g *jen.Group) {
				for _, v := range aliases[v] {
					g.Add(jen.Lit(v))
				}
			}))
		}
		g.Line()
	})
	f.Line()
	f.Comment("AllowedConfigurationValues matches the complete parsed value for a configuration.")
	f.Var().Id("AllowedConfigurationValues").Op("=").Map(jen.String()).Op("*").Qual("regexp", "Regexp").
		ValuesFunc(func(g *jen.Group) {
			for _, key := range keys {
				if pattern, ok := patterns[key]; ok {
					g.Add(jen.Line(), jen.Lit(key), jen.Op(":"), jen.Qual("regexp", "MustCompile").Call(jen.Lit(pattern)))
				}
			}
			g.Line()
		})

	if initializers != nil {
		if err := initializers.Save(filepath.Join(configOutput, "manifest_config.gen.go")); err != nil {
			return fmt.Errorf("save configuration initializers: %w", err)
		}
	}
	if err := f.Save(filepath.Join(output, "supported_configurations.gen.go")); err != nil {
		return fmt.Errorf("error saving file: %w", err)
	}

	return nil
}

type compiledSetting struct {
	Name     string `json:"name"`
	Property string `json:"property"`
	Resolved *struct {
		Value struct {
			Value json.RawMessage `json:"value"`
		} `json:"value"`
	} `json:"resolved"`
}

func compileConfigSchema(input string) (map[string]compiledSetting, error) {
	compiler := exec.Command("cargo", "run", "--locked", "--quiet",
		"--manifest-path", "scripts/configinverter/core-schema/Cargo.toml", "--", input)
	compiler.Stderr = os.Stderr
	output, err := compiler.Output()
	if err != nil {
		return nil, fmt.Errorf("compile configuration schema: %w", err)
	}

	var compiled []compiledSetting
	if err := json.Unmarshal(output, &compiled); err != nil {
		return nil, fmt.Errorf("read compiled configuration settings: %w", err)
	}
	settings := make(map[string]compiledSetting, len(compiled))
	for _, setting := range compiled {
		settings[setting.Name] = setting
	}
	return settings, nil
}

func configInitializers(cfg *supportedConfiguration, settings map[string]compiledSetting, keys []string) (*jen.File, error) {
	const providerPath = "github.com/DataDog/dd-trace-go/v2/internal/config/provider"
	f := jen.NewFile("config")
	f.HeaderComment("Copyright 2026-Present Datadog, Inc. https://www.datadoghq.com/")
	f.HeaderComment("SPDX-License-Identifier: Apache-2.0")
	f.HeaderComment("Code generated by configinverter generate-core. DO NOT EDIT.")
	f.ImportName(providerPath, "provider")

	methods := make(map[string]string)
	for _, key := range keys {
		setting := settings[key]
		for _, implementation := range cfg.SupportedConfigurations[key] {
			if implementation.InternalPropertyName == "" {
				continue
			}
			field := setting.Property
			first, size := utf8.DecodeRuneInString(field)
			if field != implementation.InternalPropertyName || !token.IsIdentifier(field) || !unicode.IsLower(first) {
				return nil, fmt.Errorf("invalid Config field %q for %q", implementation.InternalPropertyName, key)
			}
			method := "load" + string(unicode.ToUpper(first)) + field[size:]
			if previous, exists := methods[method]; exists {
				return nil, fmt.Errorf("Config initializer %s is bound to both %q and %q", method, previous, key)
			}
			methods[method] = key
			value := json.RawMessage("null")
			if setting.Resolved != nil {
				value = setting.Resolved.Value.Value
			}
			read, err := configRead(setting.Name, implementation.Type, value)
			if err != nil {
				return nil, fmt.Errorf("initialize Config.%s from %q: %w", field, key, err)
			}
			f.Func().Params(jen.Id("c").Op("*").Id("Config")).Id(method).
				Params(jen.Id("p").Op("*").Qual(providerPath, "Provider")).
				Block(jen.Id("c").Dot(field).Op("=").Add(read))
			f.Line()
		}
	}
	return f, nil
}

func configRead(key, kind string, value json.RawMessage) (*jen.Statement, error) {
	read := jen.Id("p")
	switch kind {
	case "string":
		var fallback string
		err := json.Unmarshal(value, &fallback)
		return read.Dot("GetString").Call(jen.Lit(key), jen.Lit(fallback)), err
	case "boolean":
		var fallback bool
		err := json.Unmarshal(value, &fallback)
		return read.Dot("GetBool").Call(jen.Lit(key), jen.Lit(fallback)), err
	case "int":
		var fallback int32
		err := json.Unmarshal(value, &fallback)
		return read.Dot("GetIntWithValidator").Call(jen.Lit(key), jen.Lit(int(fallback)), jen.Nil()), err
	default:
		return nil, fmt.Errorf("unsupported singleton field type %q", kind)
	}
}

// check verifies that there is no difference between the supported configurations
// JSON file and the generated Go code. It validates:
//   - SupportedConfigurations: exact key-set match (no missing, no extra)
//   - SensitiveConfigurations: exact key-set match (no missing, no extra)
//   - keyAliases: exact alias-set match per key (no missing, no extra)
//   - AllowedConfigurationValues: exact match of the anchored regexps
//   - JSON sort order: the JSON file must be byte-identical to its canonical form
func check(input string) error {
	rawJSON, err := os.ReadFile(input)
	if err != nil {
		return fmt.Errorf("error reading JSON file: %w", err)
	}

	cfg, err := getSupportedConfigurations(input)
	if err != nil {
		return fmt.Errorf("error getting supported configuration keys: %w", err)
	}

	var failures []string
	patterns, err := allowedPatterns(cfg)
	if err != nil {
		return err
	}
	for key, pattern := range patterns {
		compiled := env.AllowedConfigurationValues[key]
		if compiled == nil || compiled.String() != pattern {
			failures = append(failures, fmt.Sprintf("AllowedConfigurationValues: %q differs from JSON", key))
		}
	}
	for key := range env.AllowedConfigurationValues {
		if _, ok := patterns[key]; !ok {
			failures = append(failures, fmt.Sprintf("AllowedConfigurationValues: %q is missing from JSON", key))
		}
	}

	// --- SupportedConfigurations: JSON ↔ generated ---
	jsonKeys := sortSupportedConfigurationsKeys(cfg)
	jsonKeySet := make(map[string]struct{}, len(jsonKeys))
	for _, k := range jsonKeys {
		jsonKeySet[k] = struct{}{}
	}
	for _, k := range jsonKeys {
		if _, ok := env.SupportedConfigurations[k]; !ok {
			failures = append(failures, fmt.Sprintf("SupportedConfigurations: %q present in JSON but missing from generated", k))
		}
	}
	for k := range env.SupportedConfigurations {
		if _, ok := jsonKeySet[k]; !ok {
			failures = append(failures, fmt.Sprintf("SupportedConfigurations: %q present in generated but missing from JSON", k))
		}
	}

	// --- SensitiveConfigurations: JSON ↔ generated ---
	sensitiveKeys := sensitiveConfigurationKeys(cfg)
	sensitiveKeySet := make(map[string]struct{}, len(sensitiveKeys))
	for _, k := range sensitiveKeys {
		sensitiveKeySet[k] = struct{}{}
	}
	for _, k := range sensitiveKeys {
		if _, ok := env.SensitiveConfigurations[k]; !ok {
			failures = append(failures, fmt.Sprintf("SensitiveConfigurations: %q is sensitive in JSON but missing from generated", k))
		}
	}
	for k := range env.SensitiveConfigurations {
		if _, ok := sensitiveKeySet[k]; !ok {
			failures = append(failures, fmt.Sprintf("SensitiveConfigurations: %q is in generated but not marked sensitive in JSON", k))
		}
	}

	// --- keyAliases: JSON ↔ generated ---
	jsonAliases := collectAliasMap(cfg)
	genAliases := env.KeyAliases
	for k, jsonList := range jsonAliases {
		genList, ok := genAliases[k]
		if !ok {
			failures = append(failures, fmt.Sprintf("keyAliases: %q has aliases in JSON but no entry in generated", k))
			continue
		}
		genSet := make(map[string]struct{}, len(genList))
		for _, a := range genList {
			genSet[a] = struct{}{}
		}
		for _, a := range jsonList {
			if _, ok := genSet[a]; !ok {
				failures = append(failures, fmt.Sprintf("keyAliases: alias %q for key %q present in JSON but missing from generated", a, k))
			}
		}
	}
	for k, genList := range genAliases {
		jsonList, ok := jsonAliases[k]
		if !ok {
			failures = append(failures, fmt.Sprintf("keyAliases: %q has aliases in generated but no aliases in JSON", k))
			continue
		}
		jsonSet := make(map[string]struct{}, len(jsonList))
		for _, a := range jsonList {
			jsonSet[a] = struct{}{}
		}
		for _, a := range genList {
			if _, ok := jsonSet[a]; !ok {
				failures = append(failures, fmt.Sprintf("keyAliases: alias %q for key %q present in generated but missing from JSON", a, k))
			}
		}
	}

	// --- JSON sort and format ---
	// Re-encode the parsed config with the canonical settings used by generate/add.
	// If the file was not sorted or was otherwise modified by hand, the bytes will differ.
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(cfg); err != nil {
		return fmt.Errorf("error re-encoding JSON for sort check: %w", err)
	}
	normalized := bytes.TrimRight(buf.Bytes(), "\n")
	// Normalize CRLF to LF before comparing: on Windows the file may be checked out
	// with CRLF line endings (git core.autocrlf), but the canonical encoding always
	// uses LF. We validate content and sort order, not platform-specific line endings.
	rawNormalized := bytes.ReplaceAll(rawJSON, []byte("\r\n"), []byte("\n"))
	if !bytes.Equal(bytes.TrimRight(rawNormalized, "\n"), normalized) {
		failures = append(failures, "JSON is not sorted or not in canonical format; run `go run ./scripts/configinverter/main.go generate` to fix")
	}

	if len(failures) > 0 {
		for _, f := range failures {
			slog.Error(f)
		}
		slog.Info("run `go run ./scripts/configinverter/main.go generate` to re-generate the supported configurations")
		return fmt.Errorf("%d discrepancy(ies) found between JSON and generated code", len(failures))
	}

	slog.Info("supported configurations JSON file and generated map are in sync")
	return nil
}

// add adds new keys to the supported configurations JSON file and re-generates the
// supported configurations map using the `generate` command.
func add(input, output string, newKeys []string) error {
	cfg, err := getSupportedConfigurations(input)
	if err != nil {
		return fmt.Errorf("error getting supported configuration keys: %w", err)
	}

	filteredKeys := []string{}
	for _, k := range newKeys {
		// Filter out keys that don't start with DD_ or OTEL_
		if strings.HasPrefix(strings.ToUpper(k), "DD_") || strings.HasPrefix(strings.ToUpper(k), "OTEL_") {
			filteredKeys = append(filteredKeys, strings.ToUpper(k))
		}
	}

	missingKeys := []string{}
	for _, k := range filteredKeys {
		_, ok := cfg.SupportedConfigurations[k]
		if !ok {
			missingKeys = append(missingKeys, k)
		} else {
			slog.Info("key already exists", "key", k)
		}
	}

	if len(missingKeys) == 0 {
		slog.Info("no new keys to add")
		return nil
	}

	slog.Info("adding missing keys", "count", len(missingKeys), "keys", missingKeys)

	err = addSupportedConfigurationsKeys(input, cfg, missingKeys)
	if err != nil {
		return fmt.Errorf("error adding supported configuration keys to file: %w", err)
	}

	if err := generate(input, output, false, ""); err != nil {
		return fmt.Errorf("error running generate command after adding supported configuration keys: %w", err)
	}

	return nil
}

// getSupportedConfigurationsKeys gets the supported configurations keys from the JSON file.
// It returns a sorted list of env variables.
func getSupportedConfigurationsKeys(input string) ([]string, error) {
	cfg, err := getSupportedConfigurations(input)
	if err != nil {
		return nil, fmt.Errorf("error getting supported configuration: %w", err)
	}

	return sortSupportedConfigurationsKeys(cfg), nil
}

func sortSupportedConfigurationsKeys(cfg *supportedConfiguration) []string {
	keys := []string{}
	for k := range cfg.SupportedConfigurations {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// collectAliasMap returns a map from configuration key to the union of all aliases
// defined across its implementations.
func collectAliasMap(cfg *supportedConfiguration) map[string][]string {
	result := make(map[string][]string)
	for k, impls := range cfg.SupportedConfigurations {
		var aliases []string
		for _, impl := range impls {
			aliases = append(aliases, impl.Aliases...)
		}
		if len(aliases) > 0 {
			result[k] = aliases
		}
	}
	return result
}

func allowedPatterns(cfg *supportedConfiguration) (map[string]string, error) {
	patterns := make(map[string]string)
	for name, implementations := range cfg.SupportedConfigurations {
		for _, implementation := range implementations {
			if implementation.Allowed == "" {
				continue
			}
			switch implementation.Type {
			case "string", "boolean", "int", "decimal":
			default:
				return nil, fmt.Errorf("allowed regexp requires a scalar setting for %q", name)
			}
			pattern := `\A(?:` + implementation.Allowed + `)\z`
			if _, err := regexp.Compile(pattern); err != nil {
				return nil, fmt.Errorf("invalid allowed regexp for %q: %w", name, err)
			}
			if previous, exists := patterns[name]; exists && previous != pattern {
				return nil, fmt.Errorf("multiple allowed regexps for %q", name)
			}
			patterns[name] = pattern
		}
	}
	return patterns, nil
}

// sensitiveConfigurationKeys returns the sorted list of configuration keys that have
// at least one implementation marked "sensitive": true.
func sensitiveConfigurationKeys(cfg *supportedConfiguration) []string {
	keys := []string{}
	for k, impls := range cfg.SupportedConfigurations {
		for _, impl := range impls {
			if impl.Sensitive {
				keys = append(keys, k)
				break
			}
		}
	}
	sort.Strings(keys)
	return keys
}

// getSupportedConfigurations gets the supported configurations from the JSON file.
func getSupportedConfigurations(input string) (*supportedConfiguration, error) {
	fcontent, err := os.ReadFile(input)
	if err != nil {
		return nil, fmt.Errorf("error getting supported configuration keys from embed: %w", err)
	}

	slog.Info("read file", "file", input)

	var cfg supportedConfiguration
	if err := json.Unmarshal(fcontent, &cfg); err != nil {
		return nil, fmt.Errorf("error unmarshalling supported configuration: %w", err)
	}

	return &cfg, nil
}

// addSupportedConfigurationsKeys adds new keys to the supported configurations JSON
// file.
func addSupportedConfigurationsKeys(input string, cfg *supportedConfiguration, newKeys []string) error {
	defaultValue := "FIX_ME"
	for _, k := range newKeys {
		cfg.SupportedConfigurations[k] = []configurationImplementation{
			{
				Implementation: "A",
				Type:           defaultValue,
				Default:        &defaultValue,
			},
		}
	}

	// Write the JSON file. We explicitly disable HTML escaping so strings like "&"
	// remain readable (and stable across test runs) instead of being rendered as
	// "\u0026". Map keys are still deterministically sorted by encoding/json.
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(cfg); err != nil {
		return fmt.Errorf("error marshalling supported configuration: %w", err)
	}
	jsonFile := bytes.TrimRight(buf.Bytes(), "\n")

	return os.WriteFile(input, jsonFile, 0644)
}
