// This program generates the types that wrap a commitTracker for every
// combination of the optional interfaces of chi's response writer
// (http.Flusher, http.Hijacker, io.ReaderFrom, http.Pusher), plus the FlushError
// method for the combinations without http.Flusher.
//
// A tracker must have exactly the interface set of the chi writer: a handler
// that tests for an interface must get the same answer with and without AppSec.

package main

import (
	"os"
	"text/template"
)

type tracker struct {
	Name                                       string
	Flusher, Hijacker, ReaderFrom, Pusher, Err bool
	Flags                                      string
}

func main() {
	var all []tracker
	for set := 0; set < 16; set++ {
		for _, withErr := range []bool{false, true} {
			t := tracker{
				Flusher:    set&1 != 0,
				Hijacker:   set&2 != 0,
				ReaderFrom: set&4 != 0,
				Pusher:     set&8 != 0,
				Err:        withErr,
			}
			if t.Flusher && t.Err {
				continue // FlushError is only added when there is no Flush
			}
			t.Name = "tracker"
			t.Flags = ""
			add := func(on bool, letter, flag string) {
				if !on {
					return
				}
				t.Name += letter
				if t.Flags != "" {
					t.Flags += " | "
				}
				t.Flags += flag
			}
			add(t.Flusher, "F", "hasFlusher")
			add(t.Hijacker, "H", "hasHijacker")
			add(t.ReaderFrom, "R", "hasReaderFrom")
			add(t.Pusher, "P", "hasPusher")
			add(t.Err, "E", "hasFlushError")
			if t.Flags == "" {
				t.Flags = "0"
				t.Name = "trackerBasic"
			}
			all = append(all, t)
		}
	}
	template.Must(template.New("").Parse(tpl)).Execute(os.Stdout, all)
}

var tpl = `// Unless explicitly stated otherwise all files in this repository are licensed
// under the Apache License Version 2.0.
// This product includes software developed at Datadog (https://www.datadoghq.com/).
// Copyright 2016 Datadog, Inc.

// Code generated by make_writer_appsec.go DO NOT EDIT

package chi

import (
	"bufio"
	"io"
	"net"
	"net/http"
)

// wrapCommitTracker returns the tracker type with the interface set in flags.
func wrapCommitTracker(ct *commitTracker, flags uint8) http.ResponseWriter {
	switch flags {
{{- range . }}
	case {{ .Flags }}:
		return {{ .Name }}{ct}
{{- end }}
	}
	panic("chi: invalid commit tracker interface set")
}
{{ range . }}
type {{ .Name }} struct{ *commitTracker }
{{ if .Flusher }}
func (t {{ .Name }}) Flush() { t.flush() }
{{ end }}
{{- if .Err }}
func (t {{ .Name }}) FlushError() error { return t.flushError() }
{{ end }}
{{- if .Hijacker }}
func (t {{ .Name }}) Hijack() (net.Conn, *bufio.ReadWriter, error) { return t.hijack() }
{{ end }}
{{- if .ReaderFrom }}
func (t {{ .Name }}) ReadFrom(r io.Reader) (int64, error) { return t.readFrom(r) }
{{ end }}
{{- if .Pusher }}
func (t {{ .Name }}) Push(target string, opts *http.PushOptions) error { return t.push(target, opts) }
{{ end }}
{{- end }}
`
