// Package connect provides tracing for connectrpc.com/connect clients and handlers.
//
// The interceptors created by NewInterceptor, NewClientInterceptor and NewServerInterceptor start
// a "connect.client" or "connect.server" span for every RPC and, for streaming RPCs, a
// "connect.message" span for every message sent or received (see WithStreamCalls and
// WithStreamMessages). The rpc.system tag is "connectrpc" for the Connect protocol and "grpc" for
// both gRPC and gRPC-Web. A call whose protocol connect did not report, such as a stream whose
// opening panicked or a connection that an interceptor made, has no rpc.system, status code or
// rpc.grpc.full_method tag, so no peer.service from rpc.service; its error is still recorded.
//
// A handler's panic is recorded on its call span with CodeInternal, which the client gets when the
// panic resets an HTTP/2 stream. A connect.WithRecover listed before the interceptor in the
// handler's options recovers the panic after the span has recorded it, so whatever error its
// function returns, the span reports CodeInternal; one listed after the interceptor turns the
// panic into that error, which the span records instead. Orchestrion lists the interceptor last.
//
// A connect.WithRequestGate (added in connect v1.21.0) runs before the interceptor chain, so an
// RPC that its gate rejects produces no server span. The gate's error is sent to the client, whose
// span still records it.
//
// A client stream's call span finishes once the stream has reached a terminal state and no other
// stream method is still running. The terminal states are CloseResponse, any Receive error
// (including io.EOF), a CloseRequest error, a Send error other than io.EOF (after which Receive
// reports the server's error), a panic in a stream method, and the end of the stream's context,
// whose error is not recorded if a Receive that was running when it ended returns the end of the
// stream. Close or drain client streams as connect requires, or their spans are never finished.
//
// Finished message spans are held in memory until their call span finishes, and the tracer drops
// traces of more than 100,000 spans. For streams with many messages, use WithStreamMessages(false)
// or enable partial flushing (DD_TRACE_PARTIAL_FLUSH_ENABLED).
//
// With Orchestrion, handlers built with connect's handler constructors and clients configured
// through connect.WithClientOptions are instrumented automatically. Clients generated by
// protoc-gen-connect-go v1.13.0 or later always use connect.WithClientOptions; older generators
// emit it only for methods with an idempotency_level option, or not at all.
